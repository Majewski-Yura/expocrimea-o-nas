def pick_icon(text):
    t = text.lower()
    for pat, key in ICON_RULES:
        if re.search(pat, t):
            return key
    return 'dot'


MONTHS = {'января': '01', 'февраля': '02', 'марта': '03', 'апреля': '04', 'мая': '05', 'июня': '06',
          'июля': '07', 'августа': '08', 'сентября': '09', 'октября': '10', 'ноября': '11', 'декабря': '12'}


def parse_dates(s):
    """«25 - 27 Марта 2027 года» → («25–27 марта 2027», «2027-03-25»)."""
    m = re.match(r'(\d+)(?:\s*-\s*(\d+))?\s+([А-Яа-яё]+)\s+(\d{4})', s)
    d1, d2, mon, y = m.groups()
    mon = mon.lower()
    return (f'{d1}–{d2} {mon} {y}' if d2 else f'{d1} {mon} {y}'), f'{y}-{MONTHS[mon]}-{int(d1):02d}'


